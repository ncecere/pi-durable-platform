#!/usr/bin/env bash
# Generates the Kustomize resources from the Helm chart, so the two cannot
# drift: every file marked "Generated" is `helm template` output.
#
#   deploy/scripts/generate-kustomize.sh           write the files
#   deploy/scripts/generate-kustomize.sh --check   fail if they are out of date
#
# The inputs are the values files in deploy/kustomize/generate. What is not
# generated: the kustomization.yaml files, the overlays' patches and the
# platform namespace; check-parity.sh renders both sides and compares them.
set -euo pipefail

root=$(cd "$(dirname "$0")/../.." && pwd)
chart=$root/deploy/helm/pi-durable-platform
gen=$root/deploy/kustomize/generate
kz=$root/deploy/kustomize
HELM=${HELM:-helm}
release=pi-durable-platform
namespace=pi-durable-platform

out=$kz
if [ "${1:-}" = "--check" ]; then
  out=$(mktemp -d)
  trap 'rm -rf "$out"' EXIT
  mkdir -p "$out"
elif [ -n "${1:-}" ]; then
  echo "usage: $0 [--check]" >&2
  exit 2
fi

# render <destination, relative to the output root> <template> <values file>...
render() {
  local dest=$1 tpl=$2
  shift 2
  local args=()
  for f in "$@"; do args+=(-f "$gen/$f"); done
  mkdir -p "$(dirname "$out/$dest")"
  {
    echo "# Generated by deploy/scripts/generate-kustomize.sh from the Helm chart (templates/$tpl): do not edit."
    "$HELM" template "$release" "$chart" -n "$namespace" -s "templates/$tpl" "${args[@]}" |
      grep -v -e '^# Source: ' -e '^ *helm.sh/chart: ' -e '^ *app.kubernetes.io/managed-by: Helm$' -e '^$'  # Helm 3 and 4 differ in blank lines between documents
  } >"$out/$dest"
}

for t in namespace-agents serviceaccount rbac configmap deployment service networkpolicy-platform networkpolicy-kube-api networkpolicy-agents; do
  render "base/$t.yaml" "$t.yaml" base.values.yaml
done
render overlays/agent-sandbox/sandbox.yaml sandbox.yaml base.values.yaml agent-sandbox.values.yaml
render components/cilium/ciliumnetworkpolicy.yaml networkpolicy-kube-api.yaml base.values.yaml cilium.values.yaml
render components/ingress/ingress.yaml ingress.yaml base.values.yaml ingress.values.yaml
render components/pod-disruption-budget/pdb.yaml pdb.yaml base.values.yaml pdb.values.yaml
render components/resourcequota/resourcequota.yaml resourcequota.yaml base.values.yaml resourcequota.values.yaml

if [ "${1:-}" = "--check" ]; then
  status=0
  while IFS= read -r f; do
    rel=${f#"$out"/}
    if ! diff -u "$kz/$rel" "$f" >/dev/null 2>&1; then
      echo "out of date: deploy/kustomize/$rel" >&2
      diff -u "$kz/$rel" "$f" >&2 || true
      status=1
    fi
  done < <(find "$out" -type f | sort)
  if [ "$status" -ne 0 ]; then
    echo "run deploy/scripts/generate-kustomize.sh and commit the result" >&2
  fi
  exit "$status"
fi
